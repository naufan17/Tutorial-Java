package com.tutorial;

public class Main {
    public static void main(String[] args){
        byte a = 5;
        System.out.println("Nilai short = " + a);

        short b = 10;
        System.out.println("Nilai short = " + b);

        int c = 15;
        System.out.println("Nilai integer = " + c);

        long d = 25;
        System.out.println("Nilai long = " + d);

        double e = 30.5d;
        System.out.println("Nilai double = " + e);

        float f = 35.5f;
        System.out.println("Nilai float = " + f);

        char g = 'a';
        System.out.println("Nilai char = " + g);

        boolean h = true;
        System.out.println("Nilai boolean = " + h);
    }
}
