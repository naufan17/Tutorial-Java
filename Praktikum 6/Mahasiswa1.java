class Mahasiswa1 {
    private String nim;
    private String nama;
    private String alamat;

    public void setNim(String pNim) {
        nim = pNim;
    }

    public void setNama(String pNama) {
        nama = pNama;
    }
    
    public void setAlamat(String pAlamat) {
        alamat = pAlamat;
    }
    
    public String getNim() {
        return nim;
    }
    
    public String getNama() {
        return nama;
    }
    
    public String getAlamat() {
        return alamat;
    }
}